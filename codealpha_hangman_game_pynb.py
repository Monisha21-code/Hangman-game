import random

# ==========================================
# HANGMAN GAME
# ==========================================

# Categories, words and hints
categories = {
    "Programming": {
        "python": "A popular programming language",
        "computer": "An electronic machine",
        "coding": "Writing instructions for a computer",
        "program": "A set of instructions"
    },

    "Animals": {
        "tiger": "A big wild cat",
        "elephant": "The largest land animal",
        "rabbit": "A small animal with long ears",
        "monkey": "An animal that can climb trees"
    },

    "Fruits": {
        "apple": "A red or green fruit",
        "banana": "A yellow fruit",
        "orange": "A citrus fruit",
        "mango": "A popular summer fruit"
    }
}


# ==========================================
# PLAY AGAIN
# ==========================================

while True:

    print("\n================================")
    print("        HANGMAN GAME")
    print("================================")

    # ==========================================
    # CATEGORY SELECTION
    # ==========================================

    print("\nChoose a category:")
    print("1. Programming")
    print("2. Animals")
    print("3. Fruits")

    choice = input("Enter your choice (1-3): ")

    if choice == "1":
        category = "Programming"

    elif choice == "2":
        category = "Animals"

    elif choice == "3":
        category = "Fruits"

    else:
        print("Invalid choice. Programming category selected.")
        category = "Programming"


    # ==========================================
    # SELECT RANDOM WORD
    # ==========================================

    word = random.choice(list(categories[category].keys()))

    # Get the hint for the selected word
    hint = categories[category][word]


    # ==========================================
    # HIDE THE WORD
    # ==========================================

    hidden_word = ["_"] * len(word)


    # ==========================================
    # GAME VARIABLES
    # ==========================================

    guessed_letters = []
    wrong = 0
    max_wrong = 6
    score = 0


    # ==========================================
    # HANGMAN DRAWING
    # ==========================================

    stages = [

        """
        +----+
        |    |
        O    |
       /|\\   |
       / \\   |
             |
        =========
        """,

        """
        +----+
        |    |
             |
             |
             |
             |
        =========
        """,

        """
        +----+
        |    |
        O    |
             |
             |
             |
        =========
        """,

        """
        +----+
        |    |
        O    |
        |    |
             |
             |
        =========
        """,

        """
        +----+
        |    |
        O    |
       /|    |
             |
             |
        =========
        """,

        """
        +----+
        |    |
        O    |
       /|\\   |
             |
             |
        =========
        """,

        """
        +----+
        |    |
        O    |
       /|\\   |
       / \\   |
             |
        =========
        """
    ]


    # ==========================================
    # MAIN GAME LOOP
    # ==========================================

    while wrong < max_wrong and "_" in hidden_word:

        print(stages[wrong])

        print("Category:", category)
        print("Word:", " ".join(hidden_word))
        print("Wrong guesses:", wrong, "/", max_wrong)
        print("Score:", score)

        if guessed_letters:
            print("Guessed letters:", ", ".join(guessed_letters))

        # ==========================================
        # GUESS OR HINT
        # ==========================================

        guess = input(
            "\nGuess one letter or type 'hint': "
        ).lower()


        # ==========================================
        # HINT
        # ==========================================

        if guess == "hint":

            print("💡 Hint:", hint)

            score -= 5

            continue


        # ==========================================
        # CHECK INPUT
        # ==========================================

        if len(guess) != 1 or not guess.isalpha():

            print("❌ Please enter only ONE letter.")

            continue


        # ==========================================
        # CHECK REPEATED LETTER
        # ==========================================

        if guess in guessed_letters:

            print("⚠️ You already guessed that letter!")

            continue


        # Add guess to list
        guessed_letters.append(guess)


        # ==========================================
        # CORRECT GUESS
        # ==========================================

        if guess in word:

            print("✅ Correct guess!")

            for i in range(len(word)):

                if word[i] == guess:

                    hidden_word[i] = guess

            score += 10


        # ==========================================
        # WRONG GUESS
        # ==========================================

        else:

            print("❌ Wrong guess!")

            wrong += 1

            score -= 2


    # ==========================================
    # GAME RESULT
    # ==========================================

    if "_" not in hidden_word:

        print("\n================================")
        print("        🎉 YOU WON! 🎉")
        print("================================")

        print("The word was:", word)
        print("Your final score:", score)

    else:

        print(stages[6])

        print("\n================================")
        print("        💀 GAME OVER")
        print("================================")

        print("The word was:", word)
        print("Your final score:", score)


    # ==========================================
    # PLAY AGAIN
    # ==========================================

    play_again = input(
        "\nDo you want to play again? (yes/no): "
    ).lower()

    if play_again != "yes":

        print("\nThank you for playing Hangman! 😊")

        break